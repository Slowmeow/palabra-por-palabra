const escHtml = (s) =>
  String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);

let cur = "en";
let rules = new Intl.PluralRules("en");

export function setUiLang(code) {
  cur = STR[code] ? code : "en";
  rules = new Intl.PluralRules(cur);
  document.documentElement.lang = cur;
}

export const uiLang = () => cur;

function pick(key, n) {
  let s = STR[cur][key] ?? STR.en[key];
  if (s == null) return key;
  if (typeof s === "object") s = s[rules.select(Number(n) || 0)] ?? s.other;
  return s;
}

function render(key, vars, escape, raw = []) {
  return pick(key, vars.n).replace(/\{(\w+)\}/g, (m, k) => {
    if (!(k in vars)) return m;
    const v = vars[k];
    const s = typeof v === "number" ? v.toLocaleString(cur) : String(v ?? "");
    return escape && !raw.includes(k) ? escHtml(s) : s;
  });
}

// Plain text: for textContent, toasts, confirm(). Wrap in esc() when putting it into HTML.
export const t = (key, vars = {}) => render(key, vars, false);
// HTML: the template may contain markup; values are escaped except the keys listed in raw.
export const th = (key, vars = {}, raw = []) => render(key, vars, true, raw);
